import * as path from "node:path";
import { registerProvider } from "../capability";
import { type Skill, skillCapability } from "../capability/skill";
import { type SlashCommand, slashCommandCapability } from "../capability/slash-command";
import type { LoadContext, LoadResult } from "../capability/types";
import { ensureSpecDrivenResources } from "../spec-driven/resources";
import { SPEC_DRIVEN_SKILL_PROVIDER } from "../spec-driven/skill-policy";
import { loadFilesFromDir, scanSkillsFromDir } from "./helpers";

// The ordinary OpenSpec profile manages requirements; other bundled resources remain available to its CLI.
const OPEN_SPEC_CORE_SKILLS = new Set([
	"openspec-propose",
	"openspec-explore",
	"openspec-update-change",
	"openspec-sync-specs",
	"openspec-archive-change",
]);

const OPEN_SPEC_CORE_COMMANDS = new Set(["opsx-propose", "opsx-explore", "opsx-update", "opsx-sync", "opsx-archive"]);

/** Low-priority builtins use the ordinary catalog collision rules; native autoload bypasses that catalog. */
export async function loadSpecDrivenSkills(ctx: LoadContext): Promise<LoadResult<Skill>> {
	const resources = await ensureSpecDrivenResources();
	const items: Skill[] = [];
	const warnings: string[] = [];
	for (const entry of resources.manifest.skills) {
		if (entry.source === "openspec" && !OPEN_SPEC_CORE_SKILLS.has(entry.name)) continue;
		const filePath = path.resolve(resources.root, entry.path);
		const result = await scanSkillsFromDir(ctx, {
			dir: path.dirname(filePath),
			includeSelf: true,
			providerId: SPEC_DRIVEN_SKILL_PROVIDER,
			level: "project",
			origin: `bundled-${entry.source}`,
			pluginName: entry.source,
		});
		warnings.push(...(result.warnings ?? []));
		// Only pinned manifest entries are admitted, never bootstrap hooks or unrelated sibling trees.
		for (const skill of result.items) {
			if (path.resolve(skill.path) !== filePath) continue;
			items.push({
				...skill,
				name: entry.name,
				containRoot: {
					openspec: resources.openspecRoot,
					superpowers: resources.superpowersRoot,
					jch: resources.jchRoot,
				}[entry.source],
			});
		}
	}
	return { items, warnings };
}

registerProvider<Skill>(skillCapability.id, {
	id: SPEC_DRIVEN_SKILL_PROVIDER,
	displayName: "Spec-driven resources",
	description: "Pinned OpenSpec, Superpowers and JCH skills with resource-defined discovery visibility",
	priority: 1,
	load: loadSpecDrivenSkills,
});

export async function loadSpecDrivenCommands(ctx: LoadContext): Promise<LoadResult<SlashCommand>> {
	const resources = await ensureSpecDrivenResources();
	const result = await loadFilesFromDir<SlashCommand>(
		ctx,
		path.join(resources.openspecRoot, "commands"),
		SPEC_DRIVEN_SKILL_PROVIDER,
		"project",
		{
			extensions: ["md"],
			origin: "bundled-openspec",
			transform: (name, content, filePath, source) => ({
				name: name.replace(/\.md$/, ""),
				path: filePath,
				content,
				level: "project",
				_source: source,
			}),
		},
	);
	return { ...result, items: result.items.filter(command => OPEN_SPEC_CORE_COMMANDS.has(command.name)) };
}

registerProvider<SlashCommand>(slashCommandCapability.id, {
	id: SPEC_DRIVEN_SKILL_PROVIDER,
	displayName: "Spec-driven resources",
	description: "Pinned OpenSpec core commands generated by its native Oh My Pi adapter",
	priority: 1,
	load: loadSpecDrivenCommands,
});
